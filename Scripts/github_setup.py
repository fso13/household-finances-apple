def request(method: str, path: str, payload: dict | None = None):
    url = path if path.startswith("http") else f"{API}{path}"
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Authorization", f"Bearer {TOKEN}")
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("X-GitHub-Api-Version", "2022-11-28")
    if data:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req) as response:
            body = response.read().decode()
            return json.loads(body) if body else {}
    except urllib.error.HTTPError as error:
        body = error.read().decode(errors="replace")
        print(f"HTTP {error.code} на {method} {url}: {body}", file=sys.stderr)
        raise


def ensure_labels():
    existing = {
        label["name"] for label in request("GET", "/labels?per_page=100")
    }
    for name, (color, description) in LABELS.items():
        if name in existing:
            continue
        request("POST", "/labels", {"name": name, "color": color, "description": description})
        print(f"label+ {name}")


def ensure_milestones():
    existing = {
        milestone["title"]: milestone["number"]
        for milestone in request("GET", "/milestones?state=all&per_page=100")
    }
    numbers = dict(existing)
    for title, description in MILESTONES.items():
        if title in numbers:
            continue
        created = request("POST", "/milestones", {"title": title, "description": description})
        numbers[title] = created["number"]
        print(f"milestone+ {title} (#{created['number']})")
    return numbers


def ensure_issues(milestone_numbers):
    existing = {
        issue["title"]
        for issue in request("GET", "/issues?state=all&per_page=100")
        if "pull_request" not in issue
    }
    created_issues = []
    for issue in ISSUES:
        if issue["title"] in existing:
            continue
        payload = {
            "title": issue["title"],
            "body": issue["body"],
            "labels": issue["labels"],
            "milestone": milestone_numbers[issue["milestone"]],
        }
        created = request("POST", "/issues", payload)
        created_issues.append(created)
        print(f"issue+ #{created['number']} {created['title']}")
    return created_issues


def main():
    ensure_labels()
    milestones = ensure_milestones()
    created = ensure_issues(milestones)
    with open("/tmp/gh_issues.json", "w") as handle:
        json.dump(
            [
                {"number": issue["number"], "title": issue["title"], "url": issue["html_url"]}
                for issue in created
            ],
            handle,
            ensure_ascii=False,
            indent=2,
        )
    print(f"Создано issues: {len(created)}")


if __name__ == "__main__":
    main()
